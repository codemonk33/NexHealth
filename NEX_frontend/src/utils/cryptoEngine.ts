/**
 * ─────────────────────────────────────────────────────────────────────────────
 * BioNex Crypto Engine
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Implements the BioNex E2E encryption protocol:
 *   • ECDH P-256 key pair generation       (NIST FIPS 186-4)
 *   • ECDSA P-256 proof-of-possession sign (RFC 6979 deterministic)
 *   • HKDF-SHA-256 key derivation          (RFC 5869)
 *   • ChaCha20-Poly1305 AEAD decrypt       (RFC 8439)
 *   • SHA-256 integrity verification       (NIST FIPS 180-4)
 *
 * Security invariants enforced here:
 *   1. Private key is generated only on the device — NEVER transmitted.
 *   2. Private key is exported as JWK only for SecureStore persistence.
 *      On re-import it is marked non-extractable (CryptoKey cannot be exported again).
 *   3. All intermediate secrets (shared secret, symmetric key) are zeroed
 *      in the `finally` block even when exceptions are thrown.
 *   4. Raw crypto errors are NEVER surfaced to the caller; a sanitised
 *      CryptoError with a stable error code is thrown instead, preventing
 *      timing/oracle attacks via error messages.
 *   5. AAD (`patient_id:doctor_id`) is reconstructed from server-supplied
 *      identity fields and verified by Poly1305 — any mismatch causes
 *      authenticated-decryption to fail.
 *   6. signRegistrationNonce() re-imports the same P-256 JWK under the ECDSA
 *      algorithm (separate from ECDH) as non-extractable, ensuring the signing
 *      key cannot be re-exported. The server nonce is signed with ECDSA-SHA-256.
 *
 * Crypto primitives:
 *   • crypto.subtle  — ECDH key generation, ECDH deriveBits (Hermes built-in)
 *   • @noble/hashes  — HKDF-SHA-256 (pure JS, Cure53-audited)
 *   • @noble/ciphers — ChaCha20-Poly1305 (pure JS, Cure53-audited)
 *
 * @module cryptoEngine
 */

import { hkdf } from '@noble/hashes/hkdf.js';
import { sha256 } from '@noble/hashes/sha2.js';
import { bytesToHex, hexToBytes } from '@noble/hashes/utils.js';
import { chacha20poly1305 } from '@noble/ciphers/chacha.js';

// ─── Constants ────────────────────────────────────────────────────────────────

/** HKDF info tag — MUST match the server-side Python value b'encryption_key' */
const HKDF_INFO = new TextEncoder().encode('encryption_key');

/** ChaCha20-Poly1305 nonce length as per RFC 8439 */
const NONCE_LENGTH_BYTES = 12;

/** Poly1305 authentication tag length */
const AUTH_TAG_LENGTH_BYTES = 16;

/** ECDH shared secret length for P-256 */
const ECDH_BITS = 256;

/** Derived symmetric key length (32 bytes = 256-bit ChaCha key) */
const SYMMETRIC_KEY_LENGTH = 32;

// ─── Public Types ─────────────────────────────────────────────────────────────

export interface GeneratedKeyPair {
  /** SPKI PEM — safe to transmit to the server */
  publicKeyPEM: string;
  /** JWK JSON string — store ONLY in device SecureStore, never transmit */
  privateKeyJWK: string;
  /** SHA-256 hex fingerprint of the public key for display / server reference */
  publicKeyFingerprint: string;
}

/** Payload returned by GET /encryption/sessions/{id}/encrypted-key */
export interface EncryptedSessionKeyPayload {
  session_id: string;
  patient_id: string;
  doctor_id: string;
  /** Base64-encoded ciphertext (NOT including auth tag) */
  encrypted_key: string;
  /** Base64-encoded 12-byte nonce */
  nonce: string;
  /** Base64-encoded 16-byte Poly1305 auth tag */
  auth_tag: string;
  /** PEM-encoded ephemeral ECDH P-256 public key generated by the server */
  ephemeral_public_key: string;
  /** SHA-256 hex of the plaintext session key — used for integrity verification */
  session_key_hash: string;
  expires_at: string;
}

export interface DecryptedSessionKey {
  /** 32-byte raw session key — hold in memory only, zero after use via eraseSessionKey() */
  readonly sessionKeyBytes: Uint8Array;
  /** Hex-encoded session key for passing to record-access APIs */
  readonly sessionKeyHex: string;
  readonly sessionId: string;
  readonly patientId: string;
  readonly expiresAt: string;
}

// ─── Internal Utilities ───────────────────────────────────────────────────────

/** Best-effort zeroing of a Uint8Array (limits exposure window in memory) */
function secureZero(buf: Uint8Array | null | undefined): void {
  if (buf && buf.length > 0) buf.fill(0);
}

/** Concatenate two Uint8Arrays */
function concat(a: Uint8Array, b: Uint8Array): Uint8Array {
  const out = new Uint8Array(a.length + b.length);
  out.set(a, 0);
  out.set(b, a.length);
  return out;
}

/** Decode a standard base64 string to Uint8Array */
function base64ToBytes(b64: string): Uint8Array {
  // React Native's atob is available globally via the Hermes polyfill
  const binary = atob(b64.replace(/-/g, '+').replace(/_/g, '/'));
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) out[i] = binary.charCodeAt(i);
  return out;
}

/** Encode Uint8Array to standard base64 */
function bytesToBase64(bytes: Uint8Array): string {
  let binary = '';
  for (let i = 0; i < bytes.length; i++) binary += String.fromCharCode(bytes[i]);
  return btoa(binary);
}

/**
 * Encode Uint8Array to base64url (RFC 4648 §5) — no padding, URL-safe chars.
 * Used for ECDSA signatures sent as HTTP body fields.
 */
function bytesToBase64Url(bytes: Uint8Array): string {
  return bytesToBase64(bytes)
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
}

/**
 * Decode base64url (RFC 4648 §5) to Uint8Array.
 * Handles padding restoration automatically.
 */
export function base64UrlToBytes(b64url: string): Uint8Array {
  // Add back padding
  const padding = 4 - (b64url.length % 4);
  const padded = b64url + (padding === 4 ? '' : '='.repeat(padding));

  // Convert to standard base64
  const standard = padded.replace(/-/g, '+').replace(/_/g, '/');

  // Decode
  const binary = atob(standard);
  const out = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) out[i] = binary.charCodeAt(i);
  return out;
}

/**
 * Strip PEM headers/whitespace and decode the DER body.
 * Accepts both "BEGIN PUBLIC KEY" (SPKI) and "BEGIN EC PUBLIC KEY" (SEC1).
 */
function pemToDer(pem: string): ArrayBuffer {
  const b64 = pem
    .replace(/-----BEGIN[\w\s]+-----/g, '')
    .replace(/-----END[\w\s]+-----/g, '')
    .replace(/\s+/g, '');
  const bytes = base64ToBytes(b64);
  // Slice ensures we always get a plain ArrayBuffer (not SharedArrayBuffer)
  return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer;
}

/** Encode DER bytes to PEM with 64-char line wrapping */
function derToPem(der: ArrayBuffer): string {
  const b64 = bytesToBase64(new Uint8Array(der));
  const lines = (b64.match(/.{1,64}/g) ?? []).join('\n');
  return `-----BEGIN PUBLIC KEY-----\n${lines}\n-----END PUBLIC KEY-----`;
}

// ─── Key Generation ───────────────────────────────────────────────────────────

/**
 * Generate an ECDH P-256 key pair entirely on-device.
 *
 * Uses `crypto.subtle.generateKey` (Hermes built-in, backed by the OS CSPRNG).
 * The private key is exported once as JWK for storage in SecureStore and is
 * immediately treated as device-only material.
 *
 * @throws {CryptoError} CODE: KEY_GENERATION_FAILED
 */
export async function generateKeyPair(): Promise<GeneratedKeyPair> {
  let keyPair: CryptoKeyPair;

  try {
    console.log('[CryptoEngine] generateKeyPair: calling crypto.subtle.generateKey');
    keyPair = await crypto.subtle.generateKey(
      { name: 'ECDH', namedCurve: 'P-256' },
      true,            // extractable — required to export JWK for SecureStore
      ['deriveBits'],  // only deriveBits usage; not deriveKey (prevents misuse)
    );
    console.log('[CryptoEngine] generateKeyPair: key generation successful', keyPair);
  } catch (err) {
    console.error('[CryptoEngine] generateKeyPair: key generation failed', err);
    throw new CryptoError('KEY_GENERATION_FAILED', 'Failed to generate ECDH key pair');
  }

  // Export public key as SPKI DER → PEM (sent to server)
  let publicKeyDer: ArrayBuffer;
  let privateKeyJwk: JsonWebKey;

  try {
    console.log('[CryptoEngine] generateKeyPair: exporting keys');
    [publicKeyDer, privateKeyJwk] = await Promise.all([
      crypto.subtle.exportKey('spki', keyPair.publicKey),
      crypto.subtle.exportKey('jwk', keyPair.privateKey),
    ]);
    console.log('[CryptoEngine] generateKeyPair: export successful');
  } catch (err) {
    console.error('[CryptoEngine] generateKeyPair: export failed', err);
    throw new CryptoError('KEY_EXPORT_FAILED', 'Failed to export generated key pair');
  }

  const publicKeyPEM = derToPem(publicKeyDer);

  // Compute public key fingerprint (SHA-256 of DER bytes)
  const fingerprintBuffer = await crypto.subtle.digest('SHA-256', publicKeyDer);
  const publicKeyFingerprint = bytesToHex(new Uint8Array(fingerprintBuffer));

  // Sanity-check: re-import public key to validate DER structure
  try {
    await crypto.subtle.importKey(
      'spki',
      publicKeyDer,
      { name: 'ECDH', namedCurve: 'P-256' },
      false,
      [],
    );
  } catch (err) {
    console.error('[CryptoEngine] generateKeyPair: validation failed', err);
    throw new CryptoError(
      'KEY_VALIDATION_FAILED',
      'Generated public key failed self-validation — this should never happen',
    );
  }

  return {
    publicKeyPEM,
    privateKeyJWK: JSON.stringify(privateKeyJwk),
    publicKeyFingerprint,
  };
}

/**
 * Attempt to import a PEM string as an ECDH P-256 public key.
 * Returns true if valid, false otherwise.
 * Useful for validating server-returned PEM values before use.
 */
export async function isValidEcdhPublicKeyPEM(pem: string): Promise<boolean> {
  try {
    await crypto.subtle.importKey(
      'spki',
      pemToDer(pem),
      { name: 'ECDH', namedCurve: 'P-256' },
      false,
      [],
    );
    return true;
  } catch {
    return false;
  }
}

/**
 * Compute the SHA-256 fingerprint of a public key PEM.
 * The fingerprint matches the `public_key_fingerprint` field returned by the server.
 */
export async function computePublicKeyFingerprint(publicKeyPEM: string): Promise<string> {
  try {
    const der = pemToDer(publicKeyPEM);
    const hash = await crypto.subtle.digest('SHA-256', der);
    return bytesToHex(new Uint8Array(hash));
  } catch {
    throw new CryptoError('FINGERPRINT_FAILED', 'Failed to compute key fingerprint');
  }
}

// ─── Registration Proof-of-Possession ────────────────────────────────────────

/**
 * Sign a server-issued registration nonce with the device's ECDH private key
 * using ECDSA-SHA-256. This proves the caller genuinely holds the private key
 * that corresponds to the public key being registered.
 *
 * Security design:
 *   • The same P-256 key material is imported under the ECDSA algorithm —
 *     Web Crypto API allows this because P-256 supports both ECDH and ECDSA.
 *   • The re-imported ECDSA key is non-extractable (`extractable: false`)
 *     so it cannot be re-exported even within this call.
 *   • The nonce is treated as raw UTF-8 bytes before signing — no hashing
 *     by us; ECDSA-SHA-256 hashes internally.
 *   • Raw crypto errors are caught and replaced with CryptoError codes to
 *     prevent oracle attacks via stack traces.
 *
 * @param nonce         - 64-char hex string received from GET /keypairs/registration-challenge
 * @param privateKeyJWK - JWK string from SecureStore (the device's ECDH P-256 private key)
 * @returns             - Object with base64url-encoded signature and raw signature bytes
 *
 * @throws {CryptoError}
 *   INVALID_PRIVATE_KEY — JWK is malformed or not a P-256 key
 *   NONCE_SIGN_FAILED   — ECDSA signing operation failed
 */
export async function signRegistrationNonce(
  nonce: string,
  privateKeyJWK: string,
): Promise<{ signatureB64Url: string; signatureBytes: Uint8Array }> {
  if (!nonce || nonce.length < 32) {
    throw new CryptoError('NONCE_SIGN_FAILED', 'Registration nonce is missing or too short');
  }

  // ── 1. Parse and validate JWK ──────────────────────────────────────────────
  let jwk: JsonWebKey;
  try {
    jwk = JSON.parse(privateKeyJWK) as JsonWebKey;
  } catch {
    throw new CryptoError('INVALID_PRIVATE_KEY', 'Private key data is corrupted or unreadable');
  }

  if (jwk.kty !== 'EC' || jwk.crv !== 'P-256' || !jwk.d) {
    throw new CryptoError('INVALID_PRIVATE_KEY', 'Private key is not a valid P-256 key with private component');
  }

  // ── 2. Re-import under ECDSA (non-extractable) ─────────────────────────────
  // We strip the ECDH-specific key_ops to avoid algorithm mismatch errors.
  // The underlying key bytes are identical — only the algorithm context changes.
  const { key_ops: _unusedOps, ...jwkBase } = jwk;
  void _unusedOps; // explicitly consumed to satisfy linter

  let ecdsaKey: CryptoKey;
  try {
    ecdsaKey = await crypto.subtle.importKey(
      'jwk',
      { ...jwkBase, key_ops: ['sign'] },
      { name: 'ECDSA', namedCurve: 'P-256' },
      false,       // non-extractable — cannot be re-exported from this scope
      ['sign'],
    );
  } catch {
    throw new CryptoError('INVALID_PRIVATE_KEY', 'Failed to import private key for ECDSA signing');
  }

  // ── 3. Sign the nonce bytes ────────────────────────────────────────────────
  // nonce is ASCII hex from the server — encode as UTF-8 bytes before signing.
  // The server must verify with the same encoding: bytes(nonce_hex_string, 'utf-8').
  const nonceBytes = new TextEncoder().encode(nonce);

  let signatureBuffer: ArrayBuffer;
  try {
    signatureBuffer = await crypto.subtle.sign(
      { name: 'ECDSA', hash: { name: 'SHA-256' } },
      ecdsaKey,
      nonceBytes,
    );
  } catch {
    throw new CryptoError('NONCE_SIGN_FAILED', 'ECDSA signing operation failed');
  }

  // ── 4. Encode as base64url ─────────────────────────────────────────────────
  // Web Crypto outputs IEEE P1363 format (r ∥ s, 64 bytes for P-256).
  // Server should accept P1363 or DER — document which format your backend expects.
  // P1363 (raw r∥s) is simpler; DER conversion is not needed unless backend requires it.
  const signatureBytes = new Uint8Array(signatureBuffer);
  const signatureB64Url = bytesToBase64Url(signatureBytes);
  return { signatureB64Url, signatureBytes };
}

// ─── Session Key Decryption ───────────────────────────────────────────────────

/**
 * Client-side decryption of an encrypted session key payload (Phase 3A).
 *
 * Protocol (MUST match server-side KeyExchangeManager exactly):
 *
 *   shared_secret = ECDH(doctor_private_key, ephemeral_public_key)     [P-256]
 *   symmetric_key = HKDF-SHA256(ikm=shared_secret, salt=∅,
 *                               info=b'encryption_key', length=32)     [RFC 5869]
 *   aad           = f"{patient_id}:{doctor_id}".encode()               [UTF-8]
 *   plaintext     = ChaCha20-Poly1305-Decrypt(
 *                     key=symmetric_key, nonce=nonce,
 *                     ciphertext=encrypted_key ∥ auth_tag, aad=aad)    [RFC 8439]
 *   assert SHA-256(plaintext) == session_key_hash                      [integrity]
 *
 * All intermediate secrets are zeroed in the finally block.
 *
 * @param payload  - Full payload from GET /sessions/{id}/encrypted-key
 * @param privateKeyJWK - JWK JSON string retrieved from SecureStore
 * @returns DecryptedSessionKey — caller must call eraseSessionKey() after use
 *
 * @throws {CryptoError}
 *   INVALID_PRIVATE_KEY    — JWK string is malformed or not an ECDH P-256 key
 *   INVALID_EPHEMERAL_KEY  — Server-returned ephemeral PEM is invalid
 *   INVALID_PAYLOAD        — Base64 fields are corrupt or wrong size
 *   DECRYPTION_FAILED      — Auth tag mismatch (tampered data or wrong key)
 *   INTEGRITY_CHECK_FAILED — session_key_hash does not match decrypted bytes
 */
export async function decryptSessionKey(
  payload: EncryptedSessionKeyPayload,
  privateKeyJWK: string,
): Promise<DecryptedSessionKey> {
  // Mutable references to intermediate secrets — zeroed in finally
  let sharedSecretBuf: ArrayBuffer | null = null;
  let sharedSecretBytes: Uint8Array | null = null;
  let symmetricKey: Uint8Array | null = null;

  try {
    // ── 1. Import doctor's private key (non-extractable after re-import) ──────
    let jwk: JsonWebKey;
    try {
      jwk = JSON.parse(privateKeyJWK) as JsonWebKey;
    } catch {
      throw new CryptoError('INVALID_PRIVATE_KEY', 'Private key data is corrupted or unreadable');
    }

    if (jwk.kty !== 'EC' || jwk.crv !== 'P-256') {
      throw new CryptoError('INVALID_PRIVATE_KEY', 'Private key is not an ECDH P-256 key');
    }

    let doctorPrivateKey: CryptoKey;
    try {
      doctorPrivateKey = await crypto.subtle.importKey(
        'jwk',
        jwk,
        { name: 'ECDH', namedCurve: 'P-256' },
        false,          // non-extractable — key cannot be re-exported from memory
        ['deriveBits'],
      );
    } catch {
      throw new CryptoError('INVALID_PRIVATE_KEY', 'Failed to import private key — it may be corrupted');
    }

    // ── 2. Import server's ephemeral public key ────────────────────────────────
    if (!payload.ephemeral_public_key?.startsWith('-----BEGIN')) {
      throw new CryptoError('INVALID_EPHEMERAL_KEY', 'Ephemeral public key is not in PEM format');
    }

    let ephemeralPublicKey: CryptoKey;
    try {
      ephemeralPublicKey = await crypto.subtle.importKey(
        'spki',
        pemToDer(payload.ephemeral_public_key),
        { name: 'ECDH', namedCurve: 'P-256' },
        false,
        [],
      );
    } catch {
      throw new CryptoError(
        'INVALID_EPHEMERAL_KEY',
        'Server ephemeral public key could not be imported — DER may be malformed',
      );
    }

    // ── 3. ECDH key agreement → shared secret ────────────────────────────────
    try {
      sharedSecretBuf = await crypto.subtle.deriveBits(
        { name: 'ECDH', public: ephemeralPublicKey },
        doctorPrivateKey,
        ECDH_BITS,
      );
    } catch {
      throw new CryptoError('DECRYPTION_FAILED', 'ECDH key agreement failed');
    }

    sharedSecretBytes = new Uint8Array(sharedSecretBuf);

    // ── 4. HKDF-SHA256 key derivation ─────────────────────────────────────────
    // salt=undefined maps to salt=∅ (zero-length), matching Python's salt=None
    try {
      symmetricKey = hkdf(sha256, sharedSecretBytes, undefined, HKDF_INFO, SYMMETRIC_KEY_LENGTH);
    } catch {
      throw new CryptoError('DECRYPTION_FAILED', 'HKDF key derivation failed');
    }

    // ── 5. Decode and validate ciphertext components ──────────────────────────
    let ciphertextBytes: Uint8Array;
    let nonceBytes: Uint8Array;
    let authTagBytes: Uint8Array;

    try {
      ciphertextBytes = base64ToBytes(payload.encrypted_key);
      nonceBytes      = base64ToBytes(payload.nonce);
      authTagBytes    = base64ToBytes(payload.auth_tag);
    } catch {
      throw new CryptoError('INVALID_PAYLOAD', 'Session key payload contains invalid base64 encoding');
    }

    if (nonceBytes.length !== NONCE_LENGTH_BYTES) {
      throw new CryptoError(
        'INVALID_PAYLOAD',
        `Nonce must be ${NONCE_LENGTH_BYTES} bytes, got ${nonceBytes.length}`,
      );
    }
    if (authTagBytes.length !== AUTH_TAG_LENGTH_BYTES) {
      throw new CryptoError(
        'INVALID_PAYLOAD',
        `Auth tag must be ${AUTH_TAG_LENGTH_BYTES} bytes, got ${authTagBytes.length}`,
      );
    }
    if (ciphertextBytes.length === 0) {
      throw new CryptoError('INVALID_PAYLOAD', 'Encrypted key payload is empty');
    }

    // ── 6. Build AAD — must match server: f"{patient_id}:{doctor_id}" ─────────
    if (!payload.patient_id || !payload.doctor_id) {
      throw new CryptoError('INVALID_PAYLOAD', 'patient_id or doctor_id missing from payload');
    }
    const aad = new TextEncoder().encode(`${payload.patient_id}:${payload.doctor_id}`);

    // ── 7. ChaCha20-Poly1305 AEAD decryption ──────────────────────────────────
    // @noble/ciphers expects ciphertext ∥ auth_tag as a single buffer.
    // The Poly1305 tag verification is performed automatically — if the tag
    // does not match (tampered data, wrong key, wrong AAD), an exception is thrown.
    const ciphertextWithTag = concat(ciphertextBytes, authTagBytes);

    let sessionKeyBytes: Uint8Array;
    try {
      const cipher = chacha20poly1305(symmetricKey, nonceBytes, aad);
      sessionKeyBytes = cipher.decrypt(ciphertextWithTag);
    } catch {
      // Do NOT propagate the raw decryption error — it could leak timing info
      throw new CryptoError(
        'DECRYPTION_FAILED',
        'Session key decryption failed — the data may be tampered or the key is incorrect',
      );
    }

    // ── 8. Integrity check: SHA-256(session_key) must match server hash ────────
    if (!payload.session_key_hash || payload.session_key_hash.length !== 64) {
      throw new CryptoError('INVALID_PAYLOAD', 'session_key_hash is missing or wrong length');
    }

    const hashBuf = await crypto.subtle.digest('SHA-256', sessionKeyBytes.buffer.slice(sessionKeyBytes.byteOffset, sessionKeyBytes.byteOffset + sessionKeyBytes.byteLength) as ArrayBuffer);
    const computedHash = bytesToHex(new Uint8Array(hashBuf));

    // Constant-time-ish string comparison (same length guaranteed above)
    let mismatch = 0;
    const expected = payload.session_key_hash.toLowerCase();
    for (let i = 0; i < 64; i++) {
      mismatch |= computedHash.charCodeAt(i) ^ expected.charCodeAt(i);
    }
    if (mismatch !== 0) {
      secureZero(sessionKeyBytes);
      throw new CryptoError(
        'INTEGRITY_CHECK_FAILED',
        'Session key hash mismatch — possible data integrity violation',
      );
    }

    return {
      sessionKeyBytes: sessionKeyBytes.slice(), // defensive copy
      sessionKeyHex: bytesToHex(sessionKeyBytes),
      sessionId: payload.session_id,
      patientId: payload.patient_id,
      expiresAt: payload.expires_at,
    };

  } finally {
    // ── Secure cleanup regardless of success or failure ────────────────────────
    secureZero(sharedSecretBytes);
    if (sharedSecretBuf) {
      // ArrayBuffer cannot be zeroed directly — zero via a view
      secureZero(new Uint8Array(sharedSecretBuf));
    }
    secureZero(symmetricKey);
  }
}

/**
 * Securely erase a DecryptedSessionKey from memory after use.
 *
 * Call this as soon as you no longer need the session key — typically
 * after the encrypted record has been fetched and decrypted.
 *
 * @example
 *   const key = await decryptSessionKey(payload, privateKeyJWK);
 *   try {
 *     await fetchRecord(sessionId, key.sessionKeyHex);
 *   } finally {
 *     eraseSessionKey(key);
 *   }
 */
export function eraseSessionKey(key: DecryptedSessionKey): void {
  secureZero(key.sessionKeyBytes);
  // Overwrite the mutable reference (best-effort in a GC language)
  (key as { sessionKeyHex: string }).sessionKeyHex = '';
}

// ─── Typed Error ──────────────────────────────────────────────────────────────

/**
 * Structured crypto error with a stable machine-readable code.
 *
 * Codes:
 *   KEY_GENERATION_FAILED   — crypto.subtle.generateKey failed
 *   KEY_EXPORT_FAILED       — crypto.subtle.exportKey failed
 *   KEY_VALIDATION_FAILED   — generated key failed re-import validation
 *   FINGERPRINT_FAILED      — SHA-256 fingerprint computation failed
 *   INVALID_PRIVATE_KEY     — JWK is malformed or wrong algorithm
 *   NONCE_SIGN_FAILED       — ECDSA signing for registration proof failed
 *   INVALID_EPHEMERAL_KEY   — server ephemeral PEM is malformed
 *   INVALID_PAYLOAD         — base64 fields corrupt, wrong sizes, or missing fields
 *   DECRYPTION_FAILED       — ECDH or ChaCha20-Poly1305 operation failed
 *   INTEGRITY_CHECK_FAILED  — session_key_hash does not match
 */
export class CryptoError extends Error {
  public readonly code: string;

  constructor(code: string, message: string) {
    super(message);
    this.code = code;
    this.name = 'CryptoError';
    // Preserve prototype chain in transpiled environments
    Object.setPrototypeOf(this, CryptoError.prototype);
  }
}

