/**
 * Export a public key (SPKI DER ArrayBuffer) to PEM string.
 * Standalone helper for callers that already hold a CryptoKey reference.
 *
 * @param publicKey  - An ECDH P-256 CryptoKey with the 'spki' exportable format
 * @returns SPKI PEM string
 * @throws {CryptoError} KEY_EXPORT_FAILED
 */
export async function exportPublicKeyToPEM(publicKey: CryptoKey): Promise<string> {
  try {
    const der = await crypto.subtle.exportKey('spki', publicKey);
    return derToPem(der);
  } catch {
    throw new CryptoError('KEY_EXPORT_FAILED', 'Failed to export public key to PEM');
  }
}

/**
 * Import a private key from a JWK JSON string into a non-extractable CryptoKey.
 *
 * The returned CryptoKey is marked `extractable: false` — it cannot be
 * re-exported. This prevents accidental key exfiltration after the initial
 * SecureStore write.
 *
 * @param privateKeyJWK  - JWK JSON string (from SecureStore)
 * @returns Non-extractable ECDH CryptoKey for `deriveBits`
 * @throws {CryptoError} INVALID_PRIVATE_KEY
 */
export async function importPrivateKeyFromJWK(privateKeyJWK: string): Promise<CryptoKey> {
  let jwk: JsonWebKey;
  try {
    jwk = JSON.parse(privateKeyJWK) as JsonWebKey;
  } catch {
    throw new CryptoError('INVALID_PRIVATE_KEY', 'Private key data is corrupted or unreadable');
  }

  if (jwk.kty !== 'EC' || jwk.crv !== 'P-256' || !jwk.d) {
    throw new CryptoError('INVALID_PRIVATE_KEY', 'Key is not a valid P-256 private key with private component (d)');
  }

  try {
    return await crypto.subtle.importKey(
      'jwk',
      jwk,
      { name: 'ECDH', namedCurve: 'P-256' },
      false,          // non-extractable — prevents re-export after import
      ['deriveBits'],
    );
  } catch {
    throw new CryptoError('INVALID_PRIVATE_KEY', 'Failed to import private key from JWK — it may be corrupted');
  }
}
